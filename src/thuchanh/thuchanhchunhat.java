
package thuchanh;

public class thuchanhchunhat {
    private double a;
    private double b;
    private double ketQua;

    public thuchanhchunhat(double a, double b, double ketQua) {
        this.a = a;
        this.b = b;
        this.ketQua = ketQua;
    }

    public double getA() {
        return a;
    }

    public double getB() {
        return b;
    }

    public double getKetQua() {
        return ketQua;
    }

    public void setA(double a) {
        this.a = a;
    }

    public void setB(double b) {
        this.b = b;
    }

    public void setKetQua(double ketQua) {
        this.ketQua = ketQua;
    }
}
